/**
 * The most a dream is asked to read, in estimated tokens.
 *
 * The 35B runs at 64K context, so this is a guard against a pathological file
 * rather than a normal limit. A file over this is skipped with a reason instead
 * of being half-read: a dream that sees part of a file cannot judge the whole.
 */
const DREAM_INPUT_MAX_TOKENS = 24_000;

/** The explainer line every hot file opens with. */
const EXPLAINER = "Edits you make here are saved, and a deletion is real.";

const MERGE_SYSTEM = `You are the merge step of one person's local memory consolidation, running as its own call. Your only job in this call is the merge.

You are given the current MEMORY.md and the new daily notes since the last consolidation.

Rules for this call:
- Keep every existing line and every existing value. Do not shorten, summarise, compress or reorder the file. The file is allowed to grow; reproducing it with the additions is the correct answer.
- Add a new fact as one short third-person bullet in the section where it belongs.
- Copy numbers, dates, thresholds, IDs and URLs exactly as they appear in the notes. Never normalise, round or reword them. Never reformat a date: 2026-11-13 stays 2026-11-13, 02:10Z stays 02:10Z. Do not write "Nov 13, 2026" when the note says "2026-11-13"; do not change the separators, the zero-padding or the zone suffix.
- Never record a question, a greeting, thanks, a hypothetical ("if I", "suppose", "I would") or an instruction addressed to the assistant. A question asks; it is not a fact, even when it mentions the user's own life.
- Do not duplicate something already in the file. If a line is superseded, change that line and say so in the changelog.
- Do not write or edit a '## Facts' table; it is rebuilt automatically from the values. Put facts in ordinary bullets.
- If nothing in the notes is worth keeping, return the current file unchanged with an empty changelog.

Return the complete MEMORY.md, then a line ---CHANGELOG---, then one line per change:
Added: <short line>
Changed: <short line>
Removed: <short line>
Do not add categories the contract does not include.`;

