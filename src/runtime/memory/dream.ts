/**
 * The nightly dream / consolidation pass.
 *
 * The design rule is the new memory rule, not the old dream's rule: the model
 * is the judge, the code never overrules its judgement with fact-checking,
 * source enforcement or content gates. The code guarantees only two things —
 * nothing is silently lost (a dated copy of MEMORY.md plus a git commit and a
 * changelog every time), and secrets are never written.
 *
 * Compaction is split into two calls with one job each, because asking one call
 * to preserve everything *and* drop detail lets the preservation prior win:
 *
 * 1. **merge** — add the daily delta to the current file. No size target; the
 *    file is allowed to grow and reproducing it with the additions is correct.
 * 2. **compress** — rewrite the (larger) file's prose under a hard budget. It
 *    gets no new facts; the exact values live in a code-built verbatim ledger
 *    that is inserted by code, never regenerated by the model. Compression runs
 *    on 2-4 sections in parallel and is never re-applied to its own output.
 *
 * The intermediate merged file is written under `staging/` for audit and is
 * never injected. `MEMORY.md` is replaced atomically only after the
 * deterministic fidelity check passes (every ledger fact present, no value that
 * is absent from the source, no value moved away from its neighbours).
 *
 * The dreamer is intended to be the 35B. The merge call may think; the
 * compression call runs with thinking off and a hard output cap.
 */

