const COMPRESS_SYSTEM = `You are the compression step of one person's local memory consolidation, running as its own call. Your only job in this call is compression.

The exact values (numbers, dates, IDs, URLs and negation rules) are already carried in a code-built table that will be inserted above your text. Your prose must contain no digit and no URL at all: the table owns them.

Rules for this call:
- Rewrite each section below from scratch, in terse third-person notes. Do not copy the input. Do not merge anything in; there are no new facts in this call.
- Keep every distinct durable fact, preference, commitment, decision and negation rule the section states, in shorter words.
- Drop repetition, restatement, history, examples and anything already in the table.
- Output each section under its exact '## <section>' heading, in the order given. No other headings, no changelog, no commentary.
- Write at most three short lines per section. Never omit a heading: if a section has nothing left, keep the heading with one short line.
- The hard limit is a ceiling, not a target: stay well under it.`;

const STRICT_SUFFIX = `

STRICT RETRY: the previous answer was over the budget or contained digits. Rewrite again, shorter, with no digits and no URLs anywhere. Obey the token ceiling exactly.`;

/** Split a dream answer into the new file and the changelog. */
export function parseDreamAnswer(
	answer: string,
	options: { requiredSections?: readonly string[] } = {},
): { hot: string; changelog: string[] } {
	const match = /\n[ \t]*---CHANGELOG---[ \t]*\n?/i.exec(answer);
	if (!match) {
		throw new Error(
			"the dream model did not return a changelog; expected a line '---CHANGELOG---'",
		);
	}
	const split = answer.lastIndexOf(match[0]);
	const hot = answer.slice(0, split).trimEnd();
	const changelog = answer
		.slice(split + match[0].length)
		.split(/\r?\n/)
		.map((line) => line.trim())
		.filter((line) => line.length > 0);
	if (hot.length < 16) throw new Error("the dream answer was empty before the changelog");
	if (!/^#\s*Memory/im.test(hot)) throw new Error("the dream answer is missing the '# Memory' heading");
	const required = options.requiredSections ?? SECTION_ORDER;
	if (required.length === 0) {
		if (!/^##\s+\S/m.test(hot)) throw new Error("the dream answer has no '##' section");
	} else {
		for (const section of required) {
			const heading = section.startsWith("##") ? section : `## ${section}`;
			if (!hot.includes(heading)) throw new Error(`the dream answer is missing the section ${heading}`);
		}
	}
	return { hot: `${hot}\n`, changelog };
}

/**
 * The canonical headings the current file actually uses.
 *
 * A legacy file may have no `## Facts`; requiring it made every replacement
 * impossible. The parser now asks for the canonical headings that are present,
 * and only demands "at least one section" when the file uses none of them.
 */
export function dreamSectionNames(markdown: string): string[] {
	const names = [...String(markdown ?? "").matchAll(/^##\s+(.+?)\s*$/gm)].map((match) => match[1].trim().toLowerCase());
	return SECTION_ORDER.filter((section) => {
		const wanted = section.replace(/^##\s+/, "").toLowerCase();
		return names.some((name) => name.startsWith(wanted));
	});
}

export function dreamStateFile(paths: MemoryPaths): string {
	return path.join(paths.dir, "state.json");
}

interface OldState {
	lastDreamAt?: string | null;
	lastDreamId?: string | null;
}

function readState(paths: MemoryPaths): OldState {
	try {
		const raw = fs.readFileSync(dreamStateFile(paths), "utf-8");
		return JSON.parse(raw) as OldState;
	} catch {
		return {};
	}
}

function writeState(paths: MemoryPaths, patch: OldState): void {
	const old = readState(paths);
	fs.writeFileSync(dreamStateFile(paths), `${JSON.stringify({ ...old, ...patch }, null, 2)}\n`, "utf-8");
}

function dreamId(now: Date): string {
	const stamp = now.toISOString().replace(/[:.]/g, "-").replace("Z", "");
	return `d_${stamp}`;
}

function clamp(value: number, low: number, high: number): number {
	return Math.max(low, Math.min(high, Math.round(value)));
}

function messageOf(error: unknown): string {
	return error instanceof Error ? error.message : String(error);
}

/** The transport may have stopped at the cap even when it returned text. */
function wasTruncated(answer: DreamAnswer, maxTokens: number | undefined): boolean {
	if (answer.truncated) return true;
	return typeof maxTokens === "number" && maxTokens > 0 && answer.usage.output >= maxTokens;
}

/**
 * Bug 2: an answer cut off at the cap must read as truncation, not as the model
 * refusing to return a changelog.
 */
function incompleteAnswer(reason: string, truncated: boolean, maxTokens: number | undefined): Error {
	if (!truncated) return new Error(reason);
	const cap = maxTokens ?? "requested";
	return new Error(
		`the output was truncated at the ${cap}-token cap before the closing sections were written, so it was not used; the previous file is kept`,
	);
}

const EMPTY_SKELETON = [
	"# Memory",
	"",
	EXPLAINER,
	"",
	"## Facts",
].join("\n");

/** The floor the assembled file needs before any prose: title, explainer, table, headings. */
function skeletonFor(names: string[]): string {
	const lines = [EMPTY_SKELETON];
	for (const name of names) {
		if (name.toLowerCase() === "facts") continue;
		lines.push(`## ${name}`);
	}
	return lines.join("\n");
}

function writeStaging(paths: MemoryPaths, name: string, text: string): string | null {
	try {
		fs.mkdirSync(paths.staging, { recursive: true });
		const file = path.join(paths.staging, name);
		fs.writeFileSync(file, text.endsWith("\n") ? text : `${text}\n`, "utf-8");
		return file;
	} catch {
		return null;
	}
}

function ledgerForChunk(ledger: Ledger, chunk: ProseChunk): string {
	const names = new Set(chunk.sections.map((section) => section.name));
	const rows: string[] = [];
	for (const area of ledger.areas) {
		if (!names.has(area.name)) continue;
		rows.push(`| ${area.name} | ${area.displays.join(", ")} |`);
	}
	return rows.join("\n");
}

function compressPrompt(chunk: ProseChunk, ledger: Ledger, budget: number, strict: boolean): string {
	const names = chunk.sections.map((section) => section.name);
	const rows = ledgerForChunk(ledger, chunk);
	return [
		`Compress these section(s): ${names.join(", ")}.`,
		"",
		`HARD LIMIT: ${budget} estimated tokens for the whole answer, headings included.`,
		strict ? "This is a strict retry: the previous answer broke the limit or wrote digits. Be shorter." : "",
		"",
		rows
			? `The values below are already in the table; do not repeat any of them in your prose:\n${rows}`
			: "This section has no exact values; the table is empty for it.",
		"",
		'INPUT (rewrite it, do not copy it):',
		'"""',
		chunk.text,
		'"""',
		"",
		`Return ${names.length === 1 ? "the section" : "each section"} under ${names.length === 1 ? "its" : "its exact"} heading, in this order:`,
		...names.map((name) => `## ${name}`),
		"",
		"No commentary after the sections.",
	]
		.filter((line) => line !== undefined)
		.join("\n");
}

interface ChunkResult {
	bodies: Map<string, string>;
	tokens: number;
	truncated: boolean;
	usage: { input: number; output: number };
}

/** One compression round: every chunk in parallel, each with a hard cap. */
async function compressRound(
	model: DreamModel,
	chunks: ProseChunk[],
	ledger: Ledger,
	proseBudget: number,
	round: number,
	think: boolean,
	signal: AbortSignal | undefined,
): Promise<{ ok: boolean; reason: string; bodies: Map<string, string>; tokens: number; usage: { input: number; output: number } }> {
	const total = Math.max(1, chunks.reduce((sum, chunk) => sum + chunk.tokens, 0));
	const settled = await Promise.allSettled(
		chunks.map(async (chunk): Promise<ChunkResult> => {
			let lastError = new Error(`compression failed for ${chunk.sections.map((section) => section.name).join(", ")}`);
			// Two attempts at most: the second is the stricter retry the contract
			// asks for. A retry is stricter in wording, never in budget —
			// shrinking an already-tight budget cannot succeed, it can only fail
			// twice. An over-budget answer is never accepted.
			for (let attempt = 1; attempt <= 2; attempt += 1) {
				const budget = Math.max(24, Math.floor((proseBudget * chunk.tokens) / total));
				const cap = Math.max(96, Math.ceil(budget * 1.35) + 48);
				const strict = round > 1 || attempt > 1;
				try {
					const answer = await model.complete({
						system: `${COMPRESS_SYSTEM}${strict ? STRICT_SUFFIX : ""}`,
						prompt: compressPrompt(chunk, ledger, budget, strict),
						signal,
						maxTokens: cap,
						think,
						json: false,
					});
					const parsed = parseChunkOutput(answer.text, chunk.sections.map((section) => section.name));
					const bodies = parsed.bodies;
					const bodyText = [...bodies.values()].join("\n");
					const digits = extractAtoms(bodyText);
					const tokens = chunk.sections.reduce(
						(sum, section) => sum + estimateTokens(`## ${section.name}\n${bodies.get(section.name) ?? ""}`),
						0,
					);
					if (!parsed.ok) throw new Error(parsed.reason);
					if (wasTruncated(answer, cap)) throw new Error(`the chunk was truncated at its ${cap}-token cap`);
					if (digits.length) {
						throw new Error(`the compressed prose repeated ${digits.length} exact value(s) the table already carries (${digits.slice(0, 3).map((atom) => atom.display).join(", ")})`);
					}
					if (tokens > budget) {
						throw new Error(`the compressed chunk is ~${tokens} tokens, over its ${budget}-token share`);
					}
					return { bodies, tokens, truncated: false, usage: answer.usage };
				} catch (error) {
					lastError = error instanceof Error ? error : new Error(String(error));
				}
			}
			throw lastError;
		}),
	);
	const bodies = new Map<string, string>();
	const usage = { input: 0, output: 0 };
	let tokens = 0;
	for (const [index, outcome] of settled.entries()) {
		if (outcome.status === "rejected") {
			return {
				ok: false,
				reason: `compression chunk ${index + 1}/${chunks.length} was rejected: ${messageOf(outcome.reason)}`,
				bodies,
				tokens,
				usage,
			};
		}
		usage.input += outcome.value.usage.input;
		usage.output += outcome.value.usage.output;
		tokens += outcome.value.tokens;
		for (const [name, body] of outcome.value.bodies) bodies.set(name, body);
	}
	return { ok: true, reason: "", bodies, tokens, usage };
}

/**
 * Assemble the final hot file: code-owned table first, then compressed prose.
 *
 * Every heading the merged file used is kept, even when its compressed body is
 * empty: the parser (and the injection) must still see the file's own shape.
 */
function assembleHot(ledger: Ledger, names: string[], bodies: Map<string, string>): string {
	const lines = ["# Memory", "", EXPLAINER, "", "## Facts", "", ledger.text.trim(), ""];
	const summary = (bodies.get("Facts summary") ?? "").trim();
	if (summary) lines.push(summary, "");
	for (const name of names) {
		if (name.toLowerCase() === "facts") continue;
		lines.push(`## ${name}`, "", (bodies.get(name) ?? "").trim(), "");
	}
	return `${lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd()}\n`;
}

/**
 * Strict sanity checks for safe memory consolidation.
 *
 * The budget is code-owned: a replacement over the tier's hard cap is refused
 * and the previous file kept. Over the target but under the cap is accepted and
 * reported, because the model's judgement owns content and the cap owns size.
 */
function dreamAccepted(hot: string, tier: MemoryTierName = "standard"): { ok: boolean; reason: string } {
	const secret = findSecret(hot);
	if (secret) return { ok: false, reason: `a credential would be recorded (${secret}); the dream is refused` };
	if (hot.trim().length < 40) return { ok: false, reason: "the dream answer was too short to be a memory document" };
	const tokens = estimateTokens(hot);
	const budget = MEMORY_TIERS[tier];
	if (tokens > budget.max) {
		return {
			ok: false,
			reason: `the replacement is ~${tokens} tokens, over the ${budget.max}-token hard cap for the ${tier} tier; the previous file is kept`,
		};
	}
	if (tokens > budget.target) {
		return { ok: true, reason: `~${tokens} tokens, above the ${budget.target}-token target for the ${tier} tier` };
	}
	return { ok: true, reason: "" };
}

function journalDream(paths: MemoryPaths, id: string, result: DreamResult): string {
	const file = path.join(paths.dreams, `${id}.md`);
	const compaction = result.compaction;
	const lines = [
		`# Dream ${id}`,
		``,
		`- started: ${result.startedAt}`,
		`- trigger: ${result.trigger}`,
		`- model: ${result.model}`,
		`- status: ${result.status}${result.reason ? ` (${result.reason})` : ""}`,
		`- duration: ${result.durationMs} ms`,
		``,
		`## Changelog`,
		``,
		...(result.changelog.length > 0 ? result.changelog.map((line) => `- ${line}`) : ["- (no change needed)"]),
		``,
		...(compaction
			? [
					`## Compaction`,
					``,
					`- distinct facts: ${compaction.factCount} (${compaction.atomCount} atoms + ${compaction.ruleCount} polarity rules)`,
					`- ledger: ~${compaction.ledgerTokens} tokens; skeleton ~${compaction.skeletonTokens}; floor ~${compaction.minimumTokens}`,
					`- prose budget: ~${compaction.proseBudget} tokens; compressed result: ~${compaction.compressedTokens}`,
					`- target ${compaction.targetTokens} / hard cap ${compaction.maxTokens}; feasible ${compaction.feasible}; target feasible ${compaction.targetFeasible}`,
					`- chunks: ${compaction.chunks}; strict retries: ${compaction.retries}`,
					`- atoms in/out: ${compaction.atomsIn}/${compaction.atomsOut}`,
					`- phase ms: merge ${compaction.phaseMs.merge}, compress ${compaction.phaseMs.compress}, verify ${compaction.phaseMs.verify}`,
					`- staging: ${compaction.staging.merged ?? "none"} / ${compaction.staging.compressed ?? "none"}`,
					``,
				]
			: []),
		`## Files changed`,
		``,
		...result.filesChanged.map((file) => `- ${file}`),
	];
	fs.writeFileSync(file, `${lines.join("\n")}\n`, "utf-8");
	return file;
}

export async function runDream(options: DreamOptions): Promise<DreamResult> {
	const { paths } = options;
	ensureLayout(paths.dir);
	const now = options.now ?? new Date();
	const startedAt = Date.now();
	const id = dreamId(new Date(startedAt));
	const trigger = options.trigger ?? "manual";
	const usage = { input: 0, output: 0 };
	const phaseMs = { merge: 0, compress: 0, verify: 0 };
	const staging: { merged: string | null; compressed: string | null } = { merged: null, compressed: null };
	let compaction: DreamCompaction | undefined;

	const build = (patch: Partial<DreamResult>): DreamResult => ({
		id,
		status: "skipped",
		reason: "",
		trigger,
		model: options.model?.id ?? "none",
		startedAt: new Date(startedAt).toISOString(),
		durationMs: Date.now() - startedAt,
		usage,
		changelog: [],
		journalPath: null,
		filesChanged: [],
		...(compaction ? { compaction } : {}),
		...patch,
	});

	const tier = memoryTier(options.tier ?? "standard");
	const current = readFileSafe(paths.hot)?.trim() ?? "";
	const state = readState(paths);
	const delta = readDailySince(paths.dir, state.lastDreamAt ?? null, options.dailyLimit ?? 3);
	const automatic = trigger === "backlog" || trigger === "nightly";
	if (automatic && delta.length === 0) {
		return build({ status: "skipped", reason: "no daily delta since the last consolidation" });
	}
	if (!options.model) {
		return build({ status: "skipped", reason: "no dream model provided" });
	}
	const currentTokens = estimateTokens(current);
	if (currentTokens > DREAM_INPUT_MAX_TOKENS) {
		return build({
			status: "skipped",
			reason: `the memory file is ~${currentTokens} tokens, over the ${DREAM_INPUT_MAX_TOKENS}-token dream input budget; it was not half-read`,
		});
	}

	// ---------------------------------------------------------------- phase 1: merge
	const model = options.model;
	const dailyText = delta.map((note) => `${note.day}\n${note.content.trim()}`).join("\n\n").trim().slice(0, 16_000);
	const requiredSections = dreamSectionNames(current);
	const mergePrompt = [
		current ? `Current MEMORY.md (keep all of it):\n"""\n${current}\n"""` : "Current MEMORY.md is empty.",
		dailyText ? `Daily notes since the last consolidation (the delta):\n"""\n${dailyText}\n"""` : "There are no new daily notes; return the current file unchanged.",
		"",
		"Your only job in this call is the merge. Return the full MEMORY.md now, then ---CHANGELOG--- and the changelog.",
	].join("\n");
	const mergeCap = clamp(estimateTokens(`${current}\n${dailyText}`) * 2 + 1500, 2048, 16_384);

	let mergedHot = "";
	let changelog: string[] = [];
	try {
		const mergeStart = Date.now();
		const answer = await model.complete({
			system: MERGE_SYSTEM,
			prompt: mergePrompt,
			examples: [{ role: "user", content: MERGE_EXAMPLE.user }, { role: "assistant", content: MERGE_EXAMPLE.assistant }],
			signal: options.signal,
			maxTokens: mergeCap,
			think: options.mergeThink ?? true,
			json: false,
		});
		usage.input += answer.usage.input;
		usage.output += answer.usage.output;
		const truncated = wasTruncated(answer, mergeCap);
		try {
			const parsed = parseDreamAnswer(answer.text, { requiredSections });
			mergedHot = parsed.hot.trimEnd();
			changelog = parsed.changelog;
		} catch (error) {
			return build({ status: "failed", reason: incompleteAnswer(messageOf(error), truncated, mergeCap).message });
		}
		phaseMs.merge = Date.now() - mergeStart;
	} catch (error) {
		return build({ status: "failed", reason: messageOf(error) });
	}

	// A credential is refused at the earliest phase, before any gate that could
	// report a different reason for the same answer.
	const mergeSecret = findSecret(mergedHot);
	if (mergeSecret) {
		staging.merged = writeStaging(paths, `${id}.merge.md`, mergedHot);
		return build({ status: "failed", reason: `a credential would be recorded (${mergeSecret}); the dream is refused` });
	}

	// The merge must not lose or invent a value. It may grow; it may not rewrite.
	const mergeSource = `${current}\n${dailyText}`;
	const mergeReport = checkFidelity(mergeSource, mergedHot, buildLedger(current));
	if (!mergeReport.ok) {
		staging.merged = writeStaging(paths, `${id}.merge.md`, mergedHot);
		return build({
			status: "failed",
			reason: `the merge step did not preserve the file verbatim: ${mergeReport.reasons.join("; ")}`,
		});
	}
	staging.merged = writeStaging(paths, `${id}.merge.md`, mergedHot);

	// ---------------------------------------------------------------- phase 2: compress
	const compressStart = Date.now();
	const ledger = buildLedger(mergedHot);
	const names = sectionNames(mergedHot);
	const sections = splitProseSections(mergedHot);
	const plan = planBudget(ledger, skeletonFor(names), tier);
	compaction = {
		factCount: plan.factCount,
		atomCount: plan.atomCount,
		ruleCount: plan.ruleCount,
		ledgerTokens: plan.ledgerTokens,
		skeletonTokens: plan.skeletonTokens,
		minimumTokens: plan.minimumTokens,
		targetTokens: plan.targetTokens,
		maxTokens: plan.maxTokens,
		proseBudget: plan.proseBudget,
		compressedTokens: 0,
		feasible: plan.feasible,
		targetFeasible: plan.targetFeasible,
		chunks: 0,
		retries: 0,
		atomsIn: ledger.atoms.length,
		atomsOut: 0,
		phaseMs,
		staging,
	};
	if (!plan.feasible) {
		return build({ status: "failed", reason: plan.reason });
	}

	const chunkCount = clamp(options.chunks ?? 4, 1, 4);
	const chunks = groupIntoChunks(sections, chunkCount);
	compaction.chunks = chunks.length;
	let round = await compressRound(model, chunks, ledger, plan.proseBudget, 1, options.compressThink ?? false, options.signal);
	usage.input += round.usage.input;
	usage.output += round.usage.output;
	phaseMs.compress = Date.now() - compressStart;
	if (!round.ok) {
		return build({ status: "failed", reason: round.reason });
	}

	let hot = assembleHot(ledger, names, round.bodies);
	let compressedTokens = estimateTokens(hot);

	// Never accept the first over-budget output: one stricter round, then report.
	if (compressedTokens > plan.targetTokens && chunks.length > 0) {
		compaction.retries = 1;
		const strict = await compressRound(model, chunks, ledger, plan.proseBudget, 2, options.compressThink ?? false, options.signal);
		usage.input += strict.usage.input;
		usage.output += strict.usage.output;
		if (strict.ok) {
			const candidate = assembleHot(ledger, names, strict.bodies);
			const candidateTokens = estimateTokens(candidate);
			if (candidateTokens < compressedTokens) {
				hot = candidate;
				compressedTokens = candidateTokens;
			}
		}
	}
	phaseMs.compress = Date.now() - compressStart;
	compaction.compressedTokens = compressedTokens;
	staging.compressed = writeStaging(paths, `${id}.compressed.md`, hot);

	// The structural contract for the file this dream actually wrote.
	try {
		parseDreamAnswer(`${hot}\n---CHANGELOG---\nChanged: compacted`, { requiredSections });
	} catch (error) {
		return build({ status: "failed", reason: `the compacted file is structurally invalid: ${messageOf(error)}` });
	}

	// ---------------------------------------------------------------- phase 3: fidelity
	const verifyStart = Date.now();
	const report = checkFidelity(mergedHot, hot, ledger);
	compaction.atomsOut = report.atomsPresent;
	phaseMs.verify = Date.now() - verifyStart;
	if (!report.ok) {
		return build({
			status: "failed",
			reason: `the compressed file failed the fidelity check: ${report.reasons.join("; ")}`,
		});
	}

	const gate = dreamAccepted(hot, tier);
	if (!gate.ok) {
		return build({ status: "failed", reason: gate.reason });
	}

	// ---------------------------------------------------------------- commit
	const hotBackup = backupHot(paths.dir, paths.hot, now);
	writeAtomic(paths.hot, hot);
	writeState(paths, { lastDreamAt: now.toISOString(), lastDreamId: id });
	const changelogWithCompaction = [
		...changelog,
		`Changed: compacted to ~${compressedTokens} tokens; ${plan.factCount} verbatim facts kept in the ledger`,
	];
	const reason = [plan.targetFeasible ? "" : plan.reason, gate.reason].filter(Boolean).join("; ");
	const result = build({
		status: "completed",
		reason,
		model: model.id,
		changelog: changelogWithCompaction,
		filesChanged: [paths.hot]
			.concat(hotBackup ? [hotBackup] : [])
			.concat(staging.merged ? [staging.merged] : [])
			.concat(staging.compressed ? [staging.compressed] : []),
	});
	const journal = journalDream(paths, id, result);
	const filesChanged = [...result.filesChanged, journal];
	gitCommit(
		paths.dir,
		`memory: dream ${id} (${trigger})\n\n${changelogWithCompaction.map((line) => `- ${line}`).join("\n")}\n\n` +
			`compaction: ${plan.factCount} facts, ~${compressedTokens} tokens (target ${plan.targetTokens}, cap ${plan.maxTokens})`,
	);
	return { ...result, journalPath: journal, filesChanged };
}

export interface DreamSummary {
	id: string;
	startedAt: string;
	model: string;
	status: string;
	reason: string;
	changelog: string[];
}

export function listDreams(paths: MemoryPaths, limit = 12): DreamSummary[] {
	let names: string[] = [];
	try {
		names = fs.readdirSync(paths.dreams).filter((name) => /^d_.*\.md$/.test(name)).sort().reverse();
	} catch {
		return [];
	}
	return names.slice(0, limit).map((name) => {
		const text = readFileSafe(path.join(paths.dreams, name)) ?? "";
		const startedAt = /- started:\s*(\S+)/.exec(text)?.[1] ?? "";
		const model = /- model:\s*(.+)/.exec(text)?.[1]?.trim() ?? "none";
		const status = /- status:\s*([^\n(]+)/.exec(text)?.[1]?.trim() ?? "completed";
		const reason = /- status:\s*[^\n(]*\((.*?)\)/.exec(text)?.[1]?.trim() ?? "";
		const changelog = text
			.split(/\r?\n/)
			.filter((line) => /^- (Added|Changed|Removed):/.test(line.trim()))
			.map((line) => line.trim().slice(2));
		return { id: name.replace(/\.md$/, ""), startedAt, model, status, reason, changelog };
	});
}

/** Revert a dream's git commit, leaving `history/` copies untouched. */
export interface RevertResult {
	ok: boolean;
	reason: string;
}
export function revertDream(paths: MemoryPaths, dreamId: string): RevertResult {
	const log = gitLog(paths.dir, 60);
	const target = log.find((entry) => entry.message.includes(dreamId));
	if (!target) {
		return { ok: false, reason: `No git commit mentions dream ${dreamId}; see git log in the memory directory.` };
	}
	const reverted = gitRevert(paths.dir, target.hash);
	return reverted
		? { ok: true, reason: `reverted ${target.hash} (${target.message})` }
		: { ok: false, reason: `git revert ${target.hash} failed` };
}
